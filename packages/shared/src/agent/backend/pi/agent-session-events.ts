/**
 * Pi subprocess → host event contract.
 *
 * Vendored 1:1 from @earendil-works/pi-coding-agent 1.1.0 — `AgentSessionEvent`
 * (core/agent-session.d.ts) plus the payload types it needs from
 * core/session-manager.d.ts and core/messages.d.ts. Behavior must stay
 * identical. The durable kernel (packages/pi-agent-server) synthesizes its
 * events back into these shapes for the host's event adapter.
 */
import type { AgentEvent, AgentMessage, ThinkingLevel } from '@earendil-works/pi-agent-core';
import type {
  AssistantMessage,
  ImageContent,
  Message,
  SystemMessage,
  TextContent,
  ToolResultMessage,
  Usage,
  UserMessage,
} from '@earendil-works/pi-ai';

// ============================================================
// Session entries (pi-coding-agent 1.1.0 core/session-manager.d.ts)
// ============================================================

export interface SessionEntryBase {
  type: string;
  id: string;
  parentId: string | null;
  timestamp: string;
}

export interface SessionMessageEntry extends SessionEntryBase {
  type: 'message';
  message: AgentMessage;
}

export interface ThinkingLevelChangeEntry extends SessionEntryBase {
  type: 'thinking_level_change';
  thinkingLevel: string;
}

export interface ModelChangeEntry extends SessionEntryBase {
  type: 'model_change';
  provider: string;
  modelId: string;
}

export interface UsageEntry extends SessionEntryBase {
  type: 'usage';
  /** Arbitrary usage category, such as "cache_warm". */
  kind: string;
  provider: string;
  model: string;
  usage: Usage;
  /** Optional human-readable qualifier for usage notices. */
  note?: string;
}

export interface CompactionEntry<T = unknown> extends SessionEntryBase {
  type: 'compaction';
  summary: string;
  firstKeptEntryId: string;
  tokensBefore: number;
  /** Extension-specific data (e.g., ArtifactIndex, version markers for structured compaction) */
  details?: T;
  /** Usage from the LLM call(s) that generated this summary, if available */
  usage?: Usage;
  /** True if generated by an extension, undefined/false if pi-generated (backward compatible) */
  fromHook?: boolean;
  /** Complete prompt and tool state at this compaction boundary. */
  systemMessage?: SystemMessage;
}

export interface BranchSummaryEntry<T = unknown> extends SessionEntryBase {
  type: 'branch_summary';
  fromId: string;
  summary: string;
  /** Extension-specific data (not sent to LLM) */
  details?: T;
  /** Usage from the LLM call that generated this summary, if available */
  usage?: Usage;
  /** True if generated by an extension, false if pi-generated */
  fromHook?: boolean;
}

/**
 * Custom entry for extensions to store extension-specific data in the session.
 * Use customType to identify your extension's entries.
 */
export interface CustomEntry<T = unknown> extends SessionEntryBase {
  type: 'custom';
  customType: string;
  data?: T;
}

/** Label entry for user-defined bookmarks/markers on entries. */
export interface LabelEntry extends SessionEntryBase {
  type: 'label';
  targetId: string;
  label: string | undefined;
}

/** Session metadata entry (e.g., user-defined display name). */
export interface SessionInfoEntry extends SessionEntryBase {
  type: 'session_info';
  name?: string;
}

/**
 * Custom message entry for extensions to inject messages into LLM context.
 * Unlike CustomEntry, this DOES participate in LLM context.
 */
export interface CustomMessageEntry<T = unknown> extends SessionEntryBase {
  type: 'custom_message';
  customType: string;
  content: string | (TextContent | ImageContent)[];
  details?: T;
  display: boolean;
}

/** Content that an append-only context edit may replace without changing message metadata. */
export type ContextEditableContent =
  | UserMessage['content']
  | AssistantMessage['content']
  | ToolResultMessage['content']
  | CustomMessage['content'];

/** Append-only change to one earlier entry's contribution to model context. */
export interface ContextEditEntry extends SessionEntryBase {
  type: 'context_edit';
  targetId: string;
  /** Null omits the target from model context. A value replaces only its content. */
  replacement: {
    content: ContextEditableContent;
  } | null;
}

/** Session entry - has id/parentId for tree structure (returned by "read" methods in SessionManager) */
export type SessionEntry =
  | SessionMessageEntry
  | ThinkingLevelChangeEntry
  | ModelChangeEntry
  | UsageEntry
  | CompactionEntry
  | BranchSummaryEntry
  | CustomEntry
  | CustomMessageEntry
  | ContextEditEntry
  | LabelEntry
  | SessionInfoEntry;

// ============================================================
// Custom messages (pi-coding-agent 1.1.0 core/messages.d.ts)
// ============================================================

export interface BashExecutionMessage {
  role: 'bashExecution';
  command: string;
  output: string;
  exitCode: number | undefined;
  cancelled: boolean;
  truncated: boolean;
  fullOutputPath?: string;
  timestamp: number;
}

export interface CustomMessage<T = unknown> {
  role: 'custom';
  customType: string;
  content: string | (TextContent | ImageContent)[];
  display: boolean;
  details?: T;
  timestamp: number;
}

// ============================================================
// Compaction result (pi-coding-agent 1.1.0 core/compaction/compaction.d.ts)
// ============================================================

/** Result from compact() - SessionManager adds uuid/parentUuid when saving */
export interface CompactionResult<T = unknown> {
  summary: string;
  firstKeptEntryId: string;
  tokensBefore: number;
  estimatedTokensAfter?: number;
  /** Usage from the LLM call(s) that generated this summary, if available */
  usage?: Usage;
  /** Extension-specific data (e.g., ArtifactIndex, version markers for structured compaction) */
  details?: T;
}

// ============================================================
// AgentSessionEvent (pi-coding-agent 1.1.0 core/agent-session.d.ts)
// ============================================================

/** Tool execution events of calls a tool made through `ctx.executeTool()` carry `parentToolCallId`. */
type WithParentToolCallId<E> = E extends {
  type: 'tool_execution_start' | 'tool_execution_update' | 'tool_execution_end';
}
  ? E & { parentToolCallId?: string }
  : E;

/** Session-specific events that extend the core AgentEvent */
export type AgentSessionEvent =
  | WithParentToolCallId<Exclude<AgentEvent, { type: 'agent_end' }>>
  | {
      type: 'agent_end';
      messages: AgentMessage[];
      willRetry: boolean;
    }
  | {
      type: 'agent_settled';
      aborted: boolean;
    }
  | {
      type: 'queue_update';
      steering: readonly string[];
      followUp: readonly string[];
    }
  | {
      type: 'compaction_start';
      reason: 'manual' | 'threshold' | 'overflow';
    }
  | {
      type: 'entry_appended';
      entry: SessionEntry;
    }
  | {
      type: 'session_info_changed';
      name: string | undefined;
    }
  | {
      type: 'thinking_level_changed';
      level: ThinkingLevel;
    }
  | {
      type: 'compaction_end';
      reason: 'manual' | 'threshold' | 'overflow';
      result: CompactionResult | undefined;
      aborted: boolean;
      willRetry: boolean;
      errorMessage?: string;
    }
  | {
      type: 'auto_retry_start';
      attempt: number;
      maxAttempts: number;
      delayMs: number;
      errorMessage: string;
    }
  | {
      type: 'auto_retry_end';
      success: boolean;
      attempt: number;
      finalError?: string;
    }
  | {
      type: 'summarization_retry_scheduled';
      attempt: number;
      maxAttempts: number;
      delayMs: number;
      errorMessage: string;
    }
  | {
      type: 'summarization_retry_attempt_start';
      source: 'branchSummary';
    }
  | {
      type: 'summarization_retry_attempt_start';
      source: 'compaction';
      reason: 'manual' | 'threshold' | 'overflow';
    }
  | {
      type: 'summarization_retry_finished';
    }
  | {
      type: 'bash_execution_update';
      id?: string;
      delta: string;
    };
